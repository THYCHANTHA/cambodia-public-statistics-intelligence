"""Generate docs/data_dictionary.md from the live DuckDB schema (so it cannot drift from the database)."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from cpsi.config import ROOT  # noqa: E402
from cpsi.database import queries  # noqa: E402

PURPOSE = {
    "countries": "Supported countries (11 ASEAN members + Czechia as external benchmark) with World Bank metadata.",
    "indicators": "Indicator catalogue: official API name, project unit with provenance, definition, source, licence.",
    "observations": "Long table, one row per country-indicator-year. Missing source values are NULL with status 'missing'. "
                    "Primary key (source_name, country_code, indicator_code, year).",
    "data_quality": "Per country x indicator completeness over 1960-2025, first/latest year, gaps and warnings.",
    "ingestion_log": "One row per API request bundle: URL, parameters, retrieval time, pages, records, SHA-256 of the cached response.",
}


def main() -> None:
    con = queries.connect_ro()
    out = ["# Data dictionary", "", "Generated by `scripts/generate_data_dictionary.py` from the DuckDB schema.", ""]
    for (table,) in con.execute("SELECT table_name FROM information_schema.tables WHERE table_schema='main' ORDER BY 1").fetchall():
        n = con.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
        out += [f"## `{table}` ({n:,} rows)", "", PURPOSE.get(table, ""), "", "| Column | Type | Nullable |", "|---|---|---|"]
        for name, typ, null in con.execute(
            "SELECT column_name, data_type, is_nullable FROM information_schema.columns WHERE table_name=? ORDER BY ordinal_position",
            [table],
        ).fetchall():
            out.append(f"| {name} | {typ} | {null} |")
        out.append("")
    (ROOT / "docs" / "data_dictionary.md").write_text("\n".join(out), encoding="utf-8")
    print("written")


if __name__ == "__main__":
    main()
