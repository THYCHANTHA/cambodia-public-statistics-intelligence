"""Phase 2 source validation: check the candidate indicator catalogue against the live World Bank API.

Read-only probe. Writes a JSON summary and a Markdown report to reports/validation/.
It stores per-(country, indicator) coverage only, not the observations themselves.
"""

from __future__ import annotations

import json
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://api.worldbank.org/v2"
OUT = ROOT / "reports" / "validation"
TIMEOUT = 30


def get(url: str, params: dict | None = None, tries: int = 3):
    params = {**(params or {}), "format": "json"}
    last = None
    for i in range(tries):
        try:
            r = requests.get(url, params=params, timeout=TIMEOUT)
            r.raise_for_status()
            return r.json()
        except (requests.RequestException, ValueError) as exc:
            last = exc
            time.sleep(1.5 * (i + 1))
    raise RuntimeError(f"GET {url} failed after {tries} tries: {last}")


def main() -> int:
    cfg = yaml.safe_load((ROOT / "configs" / "indicators.yaml").read_text(encoding="utf-8"))
    ctry = yaml.safe_load((ROOT / "configs" / "countries.yaml").read_text(encoding="utf-8"))
    iso3 = [c["iso3"] for c in ctry["countries"]]
    retrieved = datetime.now(UTC).isoformat(timespec="seconds")

    # Countries
    cmeta = get(f"{BASE}/country/{';'.join(iso3)}", {"per_page": 100})
    countries = {c["id"]: c for c in cmeta[1]}
    missing_c = [c for c in iso3 if c not in countries]

    results = []
    for domain, items in cfg["domains"].items():
        for item in items:
            code = item["code"]
            rec = {"code": code, "domain": domain, "requested_name": item["name"]}
            try:
                meta = get(f"{BASE}/indicator/{code}")
                if not isinstance(meta, list) or len(meta) < 2 or not meta[1]:
                    rec["status"] = "NOT_FOUND"
                    rec["detail"] = str(meta)[:200]
                    results.append(rec)
                    continue
                m = meta[1][0]
                rec.update(
                    status="OK",
                    api_name=m.get("name"),
                    unit=m.get("unit") or None,
                    source=(m.get("source") or {}).get("value"),
                    source_org=(m.get("sourceOrganization") or "")[:300],
                    note_len=len(m.get("sourceNote") or ""),
                    name_matches=m.get("name", "").strip().lower() == item["name"].strip().lower(),
                )
                data = get(
                    f"{BASE}/country/{';'.join(iso3)}/indicator/{code}",
                    {"per_page": 20000, "date": "1960:2025"},
                )
                if not isinstance(data, list) or len(data) < 2 or data[1] is None:
                    rec["status"] = "NO_DATA"
                    results.append(rec)
                    continue
                rows = data[1]
                rec["pages"] = data[0].get("pages")
                rec["total_rows"] = data[0].get("total")
                cov = {}
                for iso in iso3:
                    ys = sorted(int(r["date"]) for r in rows if r["countryiso3code"] == iso and r["value"] is not None)
                    cov[iso] = {"n": len(ys), "first": ys[0] if ys else None, "last": ys[-1] if ys else None}
                rec["coverage"] = cov
            except Exception as exc:  # noqa: BLE001 - report every failure, do not abort the run
                rec["status"] = "ERROR"
                rec["detail"] = str(exc)[:300]
            results.append(rec)
            print(rec["code"], rec["status"], flush=True)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "source_validation.json").write_text(
        json.dumps({"retrieved_at_utc": retrieved, "countries_missing": missing_c, "indicators": results}, indent=1),
        encoding="utf-8",
    )

    lines = [
        "# Source validation: World Bank Indicators API",
        "",
        f"Retrieved (UTC): {retrieved}. Window requested: 1960-2025. Generated by `scripts/validate_sources.py`.",
        "",
        "## Countries",
        "",
        "| ISO3 | Name (API) | ISO2 | Region | Income level | Capital |",
        "|---|---|---|---|---|---|",
    ]
    for iso in iso3:
        c = countries.get(iso)
        if c:
            lines.append(
                f"| {iso} | {c['name']} | {c['iso2Code']} | {c['region']['value']} | {c['incomeLevel']['value']} | {c['capitalCity']} |"
            )
        else:
            lines.append(f"| {iso} | NOT RETURNED | | | | |")
    lines += ["", "## Indicators", "", "| Code | Status | API name | Name differs? | Source | KHM n (first-last) | Countries with 0 obs |", "|---|---|---|---|---|---|---|"]
    for r in results:
        if r["status"] != "OK" or "coverage" not in r:
            lines.append(f"| {r['code']} | {r['status']} | | | | | {r.get('detail', '')} |")
            continue
        k = r["coverage"]["KHM"]
        zero = ", ".join(i for i, v in r["coverage"].items() if v["n"] == 0) or "-"
        lines.append(
            f"| {r['code']} | OK | {r['api_name']} | {'no' if r['name_matches'] else 'YES'} | {r['source']} | "
            f"{k['n']} ({k['first']}-{k['last']}) | {zero} |"
        )
    (OUT / "source_validation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    bad = [r for r in results if r["status"] != "OK"]
    print(f"done: {len(results) - len(bad)} OK, {len(bad)} problems; countries missing: {missing_c}")
    return 1 if bad or missing_c else 0


if __name__ == "__main__":
    sys.exit(main())
